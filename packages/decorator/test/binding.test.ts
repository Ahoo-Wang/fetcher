import { Fetcher, type FetchExchange } from '@ahoo-wang/fetcher';
import {
  API_METADATA_KEY,
  api,
  attribute,
  ENDPOINT_METADATA_KEY,
  PARAMETER_METADATA_KEY,
  autoGeneratedError,
  get,
  header,
  path,
  query,
} from '../src';

// What reached fetch, and the attributes interceptors saw.
let sent: { url: string; headers: Headers } | undefined;
let seenAttributes: Map<string, any> | undefined;

const fetcher = new Fetcher({ baseURL: 'https://binding.test' });
fetcher.interceptors.request.use({
  name: 'RecordAttributes',
  order: 0,
  intercept(exchange: FetchExchange) {
    seenAttributes = exchange.attributes;
  },
});

beforeEach(() => {
  sent = undefined;
  seenAttributes = undefined;
  vi.stubGlobal('fetch', async (url: string, init: RequestInit) => {
    sent = { url, headers: new Headers(init.headers as HeadersInit) };
    return new Response('{}');
  });
});

class Profile {
  constructor(readonly id: string) {}
}

@api('/items', { fetcher })
class ItemService {
  @get('/{id}')
  byId(@path('id') id: string, @query('ids') ids?: number[]): Promise<void> {
    throw autoGeneratedError(id, ids);
  }

  @get('/')
  search(
    @query() filter: { status?: string; page?: number },
    @query('since') since?: Date,
  ): Promise<void> {
    throw autoGeneratedError(filter, since);
  }

  @get('/')
  withHeaders(
    @header('Accept-Language') languages: string[],
    @header() extra: Record<string, string | undefined>,
  ): Promise<void> {
    throw autoGeneratedError(languages, extra);
  }

  @get('/')
  withAttributes(
    @attribute('user') user: { id: string },
    @attribute() attributes?: Record<string, unknown>,
    @attribute() profile?: Profile,
  ): Promise<void> {
    throw autoGeneratedError(user, attributes, profile);
  }
}

const service = new ItemService();

describe('argument binding', () => {
  it('binds an array to its name, sent as repeated query keys', async () => {
    await service.byId('a', [1, 2]);
    expect(sent?.url).toBe('https://binding.test/items/a?ids=1&ids=2');
  });

  it('spreads a plain object and sends a Date as ISO 8601', async () => {
    await service.search(
      { status: 'open', page: undefined },
      new Date(Date.UTC(2026, 0, 2)),
    );
    expect(sent?.url).toBe(
      'https://binding.test/items/?status=open&since=2026-01-02T00%3A00%3A00.000Z',
    );
  });

  it('sends an array header as a list and lets an object entry remove a header', async () => {
    await service.withHeaders(['zh', 'en'], { 'X-A': 'a', 'X-B': undefined });
    expect(sent?.headers.get('accept-language')).toBe('zh, en');
    expect(sent?.headers.get('x-a')).toBe('a');
    expect(sent?.headers.has('x-b')).toBe(false);
  });

  it('stores an explicitly named attribute under its name, merges an unnamed record', async () => {
    const profile = new Profile('p-1');
    await service.withAttributes({ id: 'u-1' }, { tenant: 't-1' }, profile);
    expect(seenAttributes?.get('user')).toEqual({ id: 'u-1' });
    expect(seenAttributes?.get('tenant')).toBe('t-1');
    // Not a plain object: stored under the inferred name, not spread.
    expect(seenAttributes?.get('profile')).toBe(profile);
    expect(seenAttributes?.has('id')).toBe(false);
  });
});

describe('executor binding', () => {
  it('keeps a subclass override of an endpoint that has no decorator of its own', async () => {
    @api('/child', { fetcher })
    class Child extends ItemService {
      override byId(): Promise<void> {
        return Promise.resolve();
      }
    }
    await new Child().byId();
    expect(sent).toBeUndefined();
  });

  it('rebinds an inherited endpoint to the subclass base path', async () => {
    @api('/child', { fetcher })
    class Child extends ItemService {}
    await new Child().byId('a');
    expect(sent?.url).toBe('https://binding.test/child/a');
  });

  it('explains a call without the service instance', async () => {
    const { byId } = service;
    await expect(byId('a')).rejects.toThrow(
      'ItemService.byId was called without its instance',
    );
  });

  it('keeps an overriding endpoint and the parent endpoint it calls via super apart', async () => {
    @api('/parent', { fetcher })
    class Parent {
      @get('/foo')
      foo(): Promise<void> {
        throw autoGeneratedError();
      }
    }
    @api('/child', { fetcher })
    class Child extends Parent {
      @get('/other')
      override foo(): Promise<void> {
        throw autoGeneratedError();
      }
      parentFoo(): Promise<void> {
        return super.foo();
      }
    }
    const child = new Child();
    await child.foo();
    expect(sent?.url).toBe('https://binding.test/child/other');
    await child.parentFoo();
    expect(sent?.url).toBe('https://binding.test/parent/foo');
    // The other order on a fresh instance.
    const other = new Child();
    await other.parentFoo();
    expect(sent?.url).toBe('https://binding.test/parent/foo');
    await other.foo();
    expect(sent?.url).toBe('https://binding.test/child/other');
  });

  it('picks up a replaced or mutated instance apiMetadata on the next call', async () => {
    const instance: any = new ItemService();
    await instance.byId('a');
    expect(sent?.url).toBe('https://binding.test/items/a');
    instance.apiMetadata = { basePath: '/replaced' };
    await instance.byId('a');
    expect(sent?.url).toBe('https://binding.test/replaced/a');
    instance.apiMetadata.basePath = '/mutated';
    await instance.byId('a');
    expect(sent?.url).toBe('https://binding.test/mutated/a');
  });

  it('binds an endpoint declared on a symbol-named method', async () => {
    const list = Symbol('list');
    @api('/symbols', { fetcher })
    class SymbolService {
      @get('/all')
      [list](): Promise<void> {
        throw autoGeneratedError();
      }
    }
    const instance = new SymbolService();
    await instance[list]();
    expect(sent?.url).toBe('https://binding.test/symbols/all');
    const unbound = instance[list];
    await expect(unbound()).rejects.toThrow(
      'SymbolService.Symbol(list) was called without its instance',
    );
  });

  it('adds no field to the service instance', async () => {
    const instance = new ItemService();
    await instance.byId('a');
    expect(Object.keys(instance)).toEqual([]);
  });
});

describe('standard (TC39) decorators', () => {
  const context = { kind: 'method', name: 'm' };

  it('are rejected by method decorators with a pointer to experimentalDecorators', () => {
    expect(() => (get('/x') as any)(() => {}, context)).toThrow(
      /experimentalDecorators/,
    );
  });

  it('are rejected by @api', () => {
    expect(() =>
      (api('/x') as any)(class {}, { kind: 'class', name: 'X' }),
    ).toThrow(/experimentalDecorators/);
  });
});

describe('inheritance across levels', () => {
  class Base {
    @get('/load')
    load(): Promise<string> {
      throw autoGeneratedError();
    }
  }

  it.each([
    ['with', true],
    ['without', false],
  ])(
    'keeps a hand-written override from a middle class %s @api in a decorated grandchild',
    async (_, decorateMiddle) => {
      api('/base', { fetcher })(Base);
      class Custom extends Base {
        override load(): Promise<string> {
          return Promise.resolve('custom');
        }
      }
      if (decorateMiddle) api('/custom', { fetcher })(Custom);
      @api('/final', { fetcher })
      class Final extends Custom {}
      expect(await new Custom().load()).toBe('custom');
      expect(await new Final().load()).toBe('custom');
      expect(sent).toBeUndefined();
    },
  );

  it('still rebinds an endpoint inherited through an undecorated middle class', async () => {
    @api('/base', { fetcher })
    class Root {
      @get('/load')
      load(): Promise<void> {
        throw autoGeneratedError();
      }
    }
    class Middle extends Root {}
    @api('/final', { fetcher })
    class Final extends Middle {}
    await new Final().load();
    expect(sent?.url).toBe('https://binding.test/final/load');
  });

  it('binds an endpoint a grandchild re-declares over a hand-written override', async () => {
    @api('/base', { fetcher })
    class Root {
      @get('/load')
      load(): Promise<void> {
        throw autoGeneratedError();
      }
    }
    class Custom extends Root {
      override load(): Promise<void> {
        return Promise.resolve();
      }
    }
    @api('/final', { fetcher })
    class Final extends Custom {
      @get('/again')
      override load(): Promise<void> {
        throw autoGeneratedError();
      }
    }
    await new Final().load();
    expect(sent?.url).toBe('https://binding.test/final/again');
  });
});

describe('executors without a declaring ancestor', () => {
  it('leaves an executor copied onto an unrelated class as it is', async () => {
    @api('/source', { fetcher })
    class Source {
      @get('/load')
      load(): Promise<void> {
        throw autoGeneratedError();
      }
    }
    class Copy {}
    Object.defineProperty(Copy.prototype, 'load', {
      value: Source.prototype.load,
      writable: true,
      configurable: true,
    });
    api('/copy', { fetcher })(Copy);
    expect(Copy.prototype.load).toBe(Source.prototype.load);
    await (Copy.prototype.load as () => Promise<void>).call(new Source());
    expect(sent?.url).toBe('https://binding.test/source/load');
  });
});

describe('two copies of the decorator module (ESM and CommonJS entries)', () => {
  // A fresh module graph stands in for the other entry point of the package:
  // it evaluates its own copy of every module, metadata keys included.
  async function otherCopy() {
    vi.resetModules();
    return import('../src');
  }

  it('binds an inherited endpoint decorated by the other copy to the subclass', async () => {
    const other = await otherCopy();
    class BaseService {
      list(limit?: number): Promise<void> {
        throw autoGeneratedError(limit);
      }
    }
    other.query('limit')(BaseService.prototype, 'list', 0);
    other.get('/items')(BaseService.prototype, 'list');
    other.api('/base', { fetcher })(BaseService);

    @api('/child', { fetcher })
    class Child extends BaseService {}
    await new Child().list(10);
    expect(sent?.url).toBe('https://binding.test/child/items?limit=10');

    class Override extends BaseService {
      @get('/other-items')
      override list(limit?: number): Promise<void> {
        throw autoGeneratedError(limit);
      }
    }
    api('/override', { fetcher })(Override);
    await new Override().list(20);
    expect(sent?.url).toBe(
      'https://binding.test/override/other-items?limit=20',
    );
  });

  it('shares the metadata keys', async () => {
    const other = await otherCopy();
    expect(other.ENDPOINT_METADATA_KEY).toBe(ENDPOINT_METADATA_KEY);
    expect(other.PARAMETER_METADATA_KEY).toBe(PARAMETER_METADATA_KEY);
    expect(other.API_METADATA_KEY).toBe(API_METADATA_KEY);
  });
});

describe('@api on classes that cannot be constructed directly', () => {
  it('decorates an abstract generic base class', async () => {
    @api('/users', { fetcher })
    abstract class BaseApi<T> {
      constructor(readonly scope?: string) {}

      @get('/{id}')
      getOne(@path('id') id: string): Promise<T | null> {
        throw autoGeneratedError(id);
      }
    }
    class Users extends BaseApi<{ id: string }> {}
    await new Users().getOne('user-1');
    expect(sent?.url).toBe('https://binding.test/users/user-1');
  });

  it('decorates a class with a private constructor and a factory', async () => {
    @api('/factory', { fetcher })
    class FactoryApi {
      private constructor() {}
      static create(): FactoryApi {
        return new FactoryApi();
      }

      @get('/one')
      getOne(): Promise<void> {
        throw autoGeneratedError();
      }
    }
    await FactoryApi.create().getOne();
    expect(sent?.url).toBe('https://binding.test/factory/one');
  });
});
