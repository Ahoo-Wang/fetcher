describe('removing a default header', () => {
  const authorized = new Fetcher({
    baseURL: 'https://binding.test',
    headers: { Authorization: 'Bearer default-token' },
  });

  @api('/headers', { fetcher: authorized })
  class HeaderService {
    @get('/header')
    byHeader(
      @header() headers: Record<string, string | null | undefined>,
    ): Promise<void> {
      throw autoGeneratedError(headers);
    }

    @get('/request')
    byRequest(@request() options: ParameterRequest): Promise<void> {
      throw autoGeneratedError(options);
    }

    @get('/endpoint', { headers: { authorization: undefined } })
    byEndpoint(): Promise<void> {
      throw autoGeneratedError();
    }
  }
  const service = new HeaderService();

  function expectNoAuthorization() {
    expect(sent?.headers.has('authorization')).toBe(false);
    for (const [, value] of sent!.headers) expect(value).not.toBe('undefined');
  }

  it('keeps the default without a removal', async () => {
    await service.byHeader({ 'X-A': 'a' });
    expect(sent?.headers.get('authorization')).toBe('Bearer default-token');
  });

  it.each([
    ['undefined', { Authorization: undefined }],
    ['null', { Authorization: null }],
    ['another spelling', { AUTHORIZATION: undefined }],
  ])('removes it through an @header() entry (%s)', async (_, headers) => {
    await service.byHeader(headers);
    expectNoAuthorization();
  });

  it('removes it through @request() headers', async () => {
    await service.byRequest({ headers: { authorization: undefined } });
    expectNoAuthorization();
  });

  it('removes it through endpoint metadata', async () => {
    await service.byEndpoint();
    expectNoAuthorization();
  });

  it('removes it through a request composed with mergeRequest', async () => {
    await authorized.get(
      '/merged',
      mergeRequest({}, { headers: { Authorization: undefined } }),
    );
    expectNoAuthorization();
    await authorized.get(
      '/merged',
      mergeRequest(
        { headers: { 'X-A': 'a' } },
        { headers: { authorization: undefined } },
      ),
    );
    expectNoAuthorization();
    expect(sent?.headers.get('x-a')).toBe('a');
  });

  it('lets a later layer set it again', async () => {
    await authorized.get(
      '/merged',
      mergeRequest(
        { headers: { Authorization: undefined } },
        { headers: { authorization: 'Bearer other' } },
      ),
    );
    expect(sent?.headers.get('authorization')).toBe('Bearer other');
  });
});

describe('inferred parameter names', () => {
  it('binds the argument after a default RegExp to its own name', async () => {
    class Service {
      read(pattern = /a,b/, id?: string, q = /\)/, page?: number): any {
        throw autoGeneratedError(pattern, id, q, page);
      }
    }
    path()(Service.prototype, 'read', 1);
    query()(Service.prototype, 'read', 3);
    get('/regex/{id}')(Service.prototype, 'read');
    api('', { fetcher })(Service);
    await new Service().read(undefined, 'item-1', undefined, 2);
    expect(sent?.url).toBe('https://binding.test/regex/item-1?page=2');
  });

  it('sends Unicode parameter names as written', async () => {
    @api('/search', { fetcher })
    class Search {
      @get()
      run(@query() 搜索: string, @query() café: string): Promise<void> {
        throw autoGeneratedError(搜索, café);
      }
    }
    await new Search().run('open', 'espresso');
    expect(sent?.url).toBe(
      'https://binding.test/search?%E6%90%9C%E7%B4%A2=open&caf%C3%A9=espresso',
    );
  });
});
