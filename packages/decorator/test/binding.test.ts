describe('arguments from another realm', () => {
  // A Node vm context stands in for a same-origin iframe.
  const foreign = <T>(source: string): T => runInNewContext(`(${source})`);

  @api('/realm', { fetcher })
  class RealmService {
    @get('/{id}')
    run(
      @path() params: { id: string },
      @query() filter: { status: string; page: number },
      @header() headers: Record<string, string>,
      @attribute() attrs: Record<string, string>,
    ): Promise<void> {
      throw autoGeneratedError(params, filter, headers, attrs);
    }

    @get('/work')
    load(signalOrController: AbortSignal | AbortController): Promise<void> {
      throw autoGeneratedError(signalOrController);
    }
  }

  it('spreads a plain object made in another realm', async () => {
    await new RealmService().run(
      foreign('{ id: "42" }'),
      foreign('{ status: "open", page: 2 }'),
      foreign('{ "X-Page": "2" }'),
      foreign('{ trace: "x" }'),
    );
    expect(sent?.url).toBe('https://binding.test/realm/42?status=open&page=2');
    expect(sent?.headers.get('x-page')).toBe('2');
    expect(seenAttributes?.get('trace')).toBe('x');
    expect(seenAttributes?.has('attrs')).toBe(false);
  });

  it('binds a class instance made in another realm whole', async () => {
    const instance = foreign<object>(
      'new (class Filter { constructor() { this.status = "open"; } })()',
    );
    await new RealmService().run({ id: '1' }, instance as any, {}, {});
    expect(sent?.url).toBe(
      'https://binding.test/realm/1?filter=%5Bobject+Object%5D',
    );
  });

  // vm contexts have no AbortController; a real one whose prototype chain
  // is a copy ending at the vm's Object.prototype keeps the internal slots
  // and fails `instanceof`, like one from an iframe.
  function asForeign<T extends object>(value: T): T {
    const foreignObjectPrototype = foreign<object>('Object.prototype');
    const copy = (prototype: object): object => {
      const parent = Object.getPrototypeOf(prototype);
      const result = Object.create(
        parent === Object.prototype ? foreignObjectPrototype : copy(parent),
      );
      Object.defineProperties(
        result,
        Object.getOwnPropertyDescriptors(prototype),
      );
      return result;
    };
    Object.setPrototypeOf(value, copy(Object.getPrototypeOf(value)));
    return value;
  }

  it.each([
    ['signal', () => asForeign(AbortSignal.abort())],
    [
      'controller',
      () => {
        const controller = asForeign(new AbortController());
        controller.abort();
        return controller;
      },
    ],
  ])('cancels with an aborted %s made in another realm', async (_, make) => {
    vi.stubGlobal('fetch', async (url: string, init: RequestInit) => {
      // As native fetch does: an aborted signal rejects before sending.
      init.signal?.throwIfAborted();
      sent = { url, headers: new Headers(init.headers as HeadersInit) };
      return new Response('{}');
    });
    const value = make();
    expect(
      value instanceof AbortSignal || value instanceof AbortController,
    ).toBe(false);
    await expect(new RealmService().load(value)).rejects.toThrow();
    expect(sent).toBeUndefined();
  });
});

describe('__proto__ as a field name', () => {
  @api('/proto', { fetcher })
  class ProtoService {
    @get('/search')
    search(@query() filter: Record<string, string>): Promise<void> {
      throw autoGeneratedError(filter);
    }

    @get('/items/{__proto__}')
    item(@path('__proto__') key: string): Promise<void> {
      throw autoGeneratedError(key);
    }

    @get('/named')
    named(@query('__proto__') value: string): Promise<void> {
      throw autoGeneratedError(value);
    }

    @get('/items/{__proto__}')
    spread(@path() params: Record<string, string>): Promise<void> {
      throw autoGeneratedError(params);
    }
  }
  const service = new ProtoService();

  it('keeps an own __proto__ key of a spread object', async () => {
    await service.search({ ['__proto__']: 'alpha', normal: 'beta' });
    expect(sent?.url).toBe(
      'https://binding.test/proto/search?__proto__=alpha&normal=beta',
    );
    await service.spread(JSON.parse('{"__proto__":"alpha"}'));
    expect(sent?.url).toBe('https://binding.test/proto/items/alpha');
  });

  it('keeps an explicit __proto__ name', async () => {
    await service.item('alpha');
    expect(sent?.url).toBe('https://binding.test/proto/items/alpha');
    await service.named('alpha');
    expect(sent?.url).toBe('https://binding.test/proto/named?__proto__=alpha');
  });
});

